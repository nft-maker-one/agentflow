_INIT_WORKFLOW_YAML = """\
# yaml-language-server: $schema=https://agentkit.dev/schema/1.0.json

id: wf_hello
version: 1
description: "Single-agent demo — echoes back the input."

agents:
  echo:
    role: thinking
    description: "Echoes its input."
    subscribe:
      - topic: q          # → agent.echo.in.q
    publish:
      - topic: reply      # → agent.echo.out.reply
    llm:
      provider: openai
      model: gpt-4o-mini

edges:
  e_in:
    from: __start__
    to: echo
    via: q
  e_out:
    from: echo
    to: __end__
    via: reply
"""

_INIT_HANDLERS_PY = '''\
"""Handler implementations for wf_hello.

Run with::

    agentkit run workflows/wf_hello.yaml \\
        --input \'{"q": "hello world"}\' \\
        --handlers handlers
"""

from agentkit import Event, agent


@agent(role="thinking", subscribe=["q"], publish=["reply"])
async def echo(ctx, event):
    text = event.payload.get("q", "")
    return [Event(topic="reply", payload={"text": text})]
'''

_INIT_README = """\
# {name}

Generated by `agentkit init`. Try::

    agentkit run workflows/wf_hello.yaml --input '{{"q": "hi"}}' --handlers handlers
"""


@app.command("init")
def init_cmd(
    name: Annotated[str, typer.Argument(help="Project directory name")],
    *,
    force: Annotated[
        bool, typer.Option("--force", help="Overwrite existing files"),
    ] = False,
) -> None:
    """Scaffold a new AgentKit project under ``./<name>/``."""
    root = Path(name)
    if root.exists() and not force:
        typer.secho(
            f"✗ {root} already exists — pass --force to overwrite",
            fg=typer.colors.RED, err=True,
        )
        raise typer.Exit(1)
    root.mkdir(parents=True, exist_ok=True)
    (root / "workflows").mkdir(exist_ok=True)
    (root / "handlers.py").write_text(_INIT_HANDLERS_PY, encoding="utf-8")
    (root / "workflows" / "wf_hello.yaml").write_text(
        _INIT_WORKFLOW_YAML, encoding="utf-8",
    )
    (root / "README.md").write_text(
        _INIT_README.format(name=name), encoding="utf-8",
    )
    typer.secho(f"✓ Created {root}/", fg=typer.colors.GREEN)
    typer.echo(f"  Try: cd {name} && agentkit run workflows/wf_hello.yaml --input '{{\"q\":\"hi\"}}' --handlers handlers")


