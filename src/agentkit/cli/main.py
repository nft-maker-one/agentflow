@app.command("serve")
def serve_cmd(
    *,
    workflows_dir: Annotated[
        Path,
        typer.Option("--workflows", help="Directory of YAML workflows to deploy"),
    ] = Path("workflows"),
    handlers_module: Annotated[
        str | None,
        typer.Option("--handlers", help="Python module with @agent / Agent definitions"),
    ] = "handlers",
    host: Annotated[str, typer.Option("--host")] = "0.0.0.0",
    port: Annotated[int, typer.Option("--port")] = 8080,
    mock: Annotated[
        bool, typer.Option("--mock", help="Force MockLLMGateway (no key needed)"),
    ] = False,
    deepseek: Annotated[
        bool, typer.Option("--deepseek", help="Use DeepSeek (reads DEEPSEEK_API_KEY)"),
    ] = False,
    mq: Annotated[
        str,
        typer.Option(
            "--mq",
            help="Message-queue backend: auto (default) | memory | kafka | redpanda. "
            "auto → kafka when AGENTKIT_BUS_BROKERS is set in env/.env, else memory.",
        ),
    ] = "auto",
    store: Annotated[
        str,
        typer.Option(
            "--store",
            help="Run-store backend: auto (default) | memory | pg. "
            "auto → pg when AGENTKIT_PG_DSN is set in env/.env, else memory.",
        ),
    ] = "auto",
    guardrail: Annotated[
        str,
        typer.Option(
            "--guardrail",
            help="Quota guardrail backend: auto (default) | memory | redis. "
            "auto → redis when AGENTKIT_GUARDRAIL_REDIS_URL is set in env/.env, else memory.",
        ),
    ] = "auto",
) -> None:
    """Boot the HTTP control plane + Web UI.

    REST endpoints under ``/api/*``; UI bundle (if built) at ``/``.
    Configure provider via ``--mock`` (no key needed) or ``--deepseek``
    (reads ``DEEPSEEK_API_KEY`` from env / ``.env``).

    For stronger durability and horizontal scale, opt into external
    backends::

        agentkit serve --mq kafka --store pg

    Both default to the zero-dependency in-process implementations, so
    plain ``agentkit serve`` needs no Docker / Kafka / Postgres.
    """
    from agentkit.api import serve as _serve  # noqa: PLC0415
    from agentkit.api.backends import (  # noqa: PLC0415
        GUARDRAIL_CHOICES,
        MQ_CHOICES,
        STORE_CHOICES,
    )

    # Validate selectors up-front so the user gets a clean error instead
    # of a stack trace from deep inside the boot sequence.
    for flag, value, choices in (
        ("--mq", mq, MQ_CHOICES),
        ("--store", store, STORE_CHOICES),
        ("--guardrail", guardrail, GUARDRAIL_CHOICES),
    ):
        if value.strip().lower() not in (*choices, "auto"):
            typer.secho(
                f"✗ invalid {flag} {value!r}; choose one of {', '.join(choices)}",
                fg=typer.colors.RED, err=True,
            )
            raise typer.Exit(2)

    typer.secho(f"→ AgentKit serve  http://{host}:{port}", fg=typer.colors.GREEN)
    typer.echo(f"  workflows : {workflows_dir}")
    typer.echo(f"  handlers  : {handlers_module}")
    typer.echo(f"  llm       : {'mock' if mock else ('deepseek' if deepseek else 'auto')}")
    _bk = lambda v: v.lower() + (" (→ resolved from env at boot)" if v.lower() == "auto" else "")  # noqa: E731
    typer.echo(f"  mq        : {_bk(mq)}")
    typer.echo(f"  store     : {_bk(store)}")
    typer.echo(f"  guardrail : {_bk(guardrail)}")
    typer.echo(f"  api docs  : http://{host}:{port}/docs")

    try:
        asyncio.run(_serve(
            workflows_dir=workflows_dir,
            handlers_module=handlers_module,
            host=host, port=port,
            use_mock_llm=mock, deepseek=deepseek,
            mq=mq, store=store, guardrail=guardrail,
        ))
    except KeyboardInterrupt:
        typer.echo("\n(stopped)")


