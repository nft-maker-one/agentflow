# ============================================================
# run  — execute via LocalRuntime
# ============================================================


@app.command("run")
def run_cmd(
    path: Annotated[Path, typer.Argument(exists=True, help="Workflow YAML file")],
    *,
    input_arg: Annotated[
        str,
        typer.Option(
            "--input", help='JSON input payload (or "@file.json")',
        ),
    ] = "{}",
    handlers_module: Annotated[
        str | None,
        typer.Option(
            "--handlers",
            help="Python module that contains @agent-decorated handlers (e.g. 'handlers')",
        ),
    ] = None,
    timeout: Annotated[
        float, typer.Option("--timeout", help="Seconds to wait for completion"),
    ] = 30.0,
    output_json: Annotated[
        bool, typer.Option("--json", help="Print final Run as JSON instead of pretty"),
    ] = False,
) -> None:
    """Run a workflow locally via the in-process runtime.

    Loads handlers from ``--handlers <module>`` so ``@agent``
    decorators register their templates before compilation.
    """
    payload = _read_input_payload(input_arg)
    if handlers_module:
        # Make CWD importable so user's local handlers.py is found.
        sys.path.insert(0, str(Path.cwd()))
        try:
            mod = importlib.import_module(handlers_module)
        except ImportError as e:
            typer.secho(
                f"✗ Could not import handlers module {handlers_module!r}: {e}",
                fg=typer.colors.RED, err=True,
            )
            raise typer.Exit(1) from None
    else:
        mod = None

    raw = load_workflow_yaml(path)
    ir, plan = compile_from_dict(raw)

    # Walk the user module for @agent-decorated functions whose
    # template_key matches one of the workflow's agents and register
    # them. ``@agent`` itself only attaches metadata; the SDK's
    # ``WorkflowDef.compile()`` does the registration — but the CLI
    # wants to support the looser "YAML + handlers.py" idiom too.
    if mod is not None:
        _register_handlers_from_module(mod, ir.id, ir.agents)

    asyncio.run(_run_workflow(ir, plan, payload, timeout, output_json))


