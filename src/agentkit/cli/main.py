@app.command("validate")
def validate_cmd(
    path: Annotated[Path, typer.Argument(exists=True, help="Workflow YAML file")],
) -> None:
    """Validate a workflow YAML against the IR schema + compile rules."""
    try:
        raw = load_workflow_yaml(path)
        ir, plan = compile_from_dict(raw)
    except IRValidationError as e:
        typer.secho(f"✗ Validation failed: {e}", fg=typer.colors.RED, err=True)
        for v in (e.violations or []):
            typer.echo(f"  • {v}", err=True)
        raise typer.Exit(1) from None
    except Exception as e:
        typer.secho(f"✗ {type(e).__name__}: {e}", fg=typer.colors.RED, err=True)
        raise typer.Exit(2) from None

    typer.secho(
        f"✓ {ir.id}@v{ir.version}  hash={ir.meta.ir_hash}  "
        f"{len(plan.agents)} agent(s)  {len(plan.bus_topics.topics)} topic(s)",
        fg=typer.colors.GREEN,
    )


# ============================================================
# compile  — output the canonicalized IR JSON
# ============================================================


@app.command("compile")
def compile_cmd(
    path: Annotated[Path, typer.Argument(exists=True, help="Workflow YAML file")],
    *,
    out: Annotated[
        Path | None,
        typer.Option("-o", "--out", help="Output JSON file (default: stdout)"),
    ] = None,
) -> None:
    """Compile a workflow YAML to canonical IR JSON."""
    raw = load_workflow_yaml(path)
    ir, _plan = compile_from_dict(raw)
    text = json.dumps(
        ir.model_dump(by_alias=True, exclude_none=True, mode="json"),
        ensure_ascii=False, indent=2, default=str,
    )
    if out is None:
        typer.echo(text)
    else:
        out.write_text(text, encoding="utf-8")
        typer.secho(f"✓ wrote {out}", fg=typer.colors.GREEN)


