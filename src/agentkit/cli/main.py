def _register_handlers_from_module(
    module, workflow_id: str, agent_keys,
) -> None:
    """Match @agent-decorated functions in ``module`` to workflow agents."""
    from agentkit.runtime import HandlerRegistry  # noqa: PLC0415
    from agentkit.runtime.executor import _FunctionExecutor  # noqa: PLC0415
    from agentkit.sdk.decorators import get_agent_meta  # noqa: PLC0415

    reg = HandlerRegistry.global_default()
    for name in dir(module):
        fn = getattr(module, name)
        meta = get_agent_meta(fn)
        if meta is None:
            continue
        if meta.template_key not in agent_keys:
            continue
        reg.register(
            workflow_id=workflow_id,
            template_key=meta.template_key,
            executor=_FunctionExecutor(meta.handler),
            replace=True,
        )


def _read_input_payload(arg: str) -> dict:
    """Decode ``--input`` value: JSON string OR ``@path/to/file.json``."""
    if arg.startswith("@"):
        return json.loads(Path(arg[1:]).read_text(encoding="utf-8"))
    return json.loads(arg)


async def _run_workflow(ir, plan, payload, timeout, output_json) -> None:
    from agentkit.bus.inprocess import InProcessEventBus  # noqa: PLC0415
    from agentkit.orchestrator import InMemoryRunStore, Orchestrator  # noqa: PLC0415
    from agentkit.runtime import AgentWorker, HandlerRegistry  # noqa: PLC0415
    from agentkit.testing.mock_llm import MockLLMGateway  # noqa: PLC0415

    bus = InProcessEventBus()
    await bus.start()
    orch = Orchestrator(bus=bus, store=InMemoryRunStore())
    await orch.start()
    await orch.deploy(ir)

    worker = AgentWorker(
        plan=plan,
        bus=bus,
        llm=MockLLMGateway(reply="(mock reply — supply real LLM via SDK to enable)"),
        handlers=HandlerRegistry.global_default(),
    )
    await worker.start()
    await asyncio.sleep(0.1)

    try:
        run = await orch.create_run(workflow_id=ir.id, input=payload)
        final = await orch.wait_for_completion(run.run_id, timeout=timeout)
    except TimeoutError:
        typer.secho(
            f"✗ Run did not complete within {timeout}s",
            fg=typer.colors.RED, err=True,
        )
        await worker.stop()
        await orch.stop()
        await bus.stop()
        raise typer.Exit(1) from None

    await worker.stop()
    await orch.stop()
    await bus.stop()

    if output_json:
        typer.echo(json.dumps(
            final.model_dump(mode="json"),
            ensure_ascii=False, indent=2, default=str,
        ))
        return

    color = typer.colors.GREEN if final.status.value == "Succeeded" else typer.colors.RED
    typer.secho(
        f"\n✓ run.{final.status.value}  run_id={final.run_id}  "
        f"({len(final.cursor.branch_log)} branch event(s))",
        fg=color,
    )
    if final.failure_reason:
        typer.echo(f"  reason: {final.failure_reason}")
    # Show the last published USER event from the bus as the user-visible
    # output. Skip synthetic ``system.*`` envelopes the orchestrator now
    # publishes for the inbox subsystem (see api/inbox.py).
    user_events = [
        e for e in bus.published if not e.topic.startswith("system.")
    ]
    if user_events:
        last = user_events[-1]
        typer.echo(f"\nlast event on {last.topic}:")
        typer.echo(json.dumps(last.payload, ensure_ascii=False, indent=2, default=str))


