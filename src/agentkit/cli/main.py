"""``agentkit`` CLI — Typer app exposing the most common commands.

Phase 1 surface (Doc09 §6, trimmed)::

    agentkit version
    agentkit init <project>
    agentkit validate <yaml-or-py>
    agentkit compile <yaml> [-o <out.json>]
    agentkit schema export [-o <out.json>]
    agentkit run <yaml> --input <json> [--handlers <module>]

Most commands are pure-Python and don't touch external services
(Kafka / Redis / SMTP). ``agentkit run`` uses the in-process
:class:`LocalRuntime` so demos work out-of-the-box.
"""

